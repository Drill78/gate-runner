import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import {
  createCheckpointRun,
  createDeveloperRun,
  DEVELOPER_PRESETS,
} from '../lib/presets.ts';
import { createBattle } from '../lib/combat.ts';
import { firepower } from '../lib/game.ts';
import { pilot, expedition } from './balance-sim.mjs';
import { ENDLESS_CURVE } from '../lib/endless.ts';

const metadata = {
  createdAt: new Date().toISOString(),
  method:
    'Actual engine, 150ms visible-state pilot. No extra heals or coins. Independent room-99 trials use the shipped developer build; stationary controls keep attacks and skills but never move. Natural staircase continuations use the complete real room-90 saves generated by v12-feedback-audit.mjs --all-routes, without replacing their equipment.',
  curve: ENDLESS_CURVE,
  hashes: Object.fromEntries(
    ['game', 'combat', 'endless', 'presets'].map((name) => [
      name,
      createHash('sha256')
        .update(readFileSync(`lib/${name}.ts`))
        .digest('hex'),
    ]),
  ),
};
const samples = [],
  natural = [];
for (const classId of ['knight', 'ranger', 'mage']) {
  for (const stationary of [false, true]) {
    const run = createDeveloperRun(
      classId,
      DEVELOPER_PRESETS.find((p) => p.id === 'ascendant'),
    );
    const result = pilot(createBattle(run), { maxTime: 300, stationary });
    samples.push({ kind: '99', classId, stationary, ...result });
    console.log(
      `99 ${classId}, stationary=${stationary}: ${result.state}, ${result.time.toFixed(1)}s, ${Math.round(result.hp)} HP`,
    );
  }
  const preset = expedition(classId, 734, 'coherent', {
    initialRun: createCheckpointRun(classId, 91, 734),
    maxFloors: 100,
    maxTime: 360,
  });
  samples.push({ kind: '91-100', classId, ...preset });
  const initialRun = JSON.parse(
    readFileSync(`artifacts/feedback-natural-${classId}-734.json`),
  ).find((r) => r.floor === 90);
  if (!initialRun)
    throw new Error(
      `Missing real room-90 build for ${classId}. Run v12-feedback-audit.mjs --all-routes first.`,
    );
  const points = [];
  const complete = expedition(classId, 734, 'coherent', {
    initialRun,
    maxFloors: 100,
    maxTime: 360,
    onCheckpoint: (r) =>
      points.push({
        room: r.floor + 1,
        dps: firepower(r).dps,
        hp: r.hp,
        maxHp: r.maxHp,
      }),
  });
  natural.push({ classId, points, ...complete });
  console.log(
    `91-100 ${classId}: preset=${preset.floor}, natural=${complete.floor}`,
  );
}
for (const [name, data] of [
  ['combat', { ...metadata, samples }],
  ['natural-stair', { ...metadata, samples: natural }],
]) {
  const body = JSON.stringify(data, null, 2);
  writeFileSync(`artifacts/v12-feedback-${name}-final.json`, body);
  writeFileSync(`docs/releases/v1.2-feedback-${name}.json`, body);
}
